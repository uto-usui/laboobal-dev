/** 札の中身を、そのみくじの文に入れ替える */
export const fillSlip = (el: HTMLElement, f: Fortune) => {
  el.querySelector('.no')!.textContent = f.no
  el.querySelector('.luck')!.textContent = f.luck
  const [a, b] = el.querySelectorAll('.uta span')
  a.textContent = f.uta[0]
  b.textContent = f.uta[1]
  el.querySelectorAll('.item').forEach((item, i) => {
    item.querySelector('dt')!.textContent = f.items[i][0]
    item.querySelector('dd')!.textContent = f.items[i][1]
  })
}
